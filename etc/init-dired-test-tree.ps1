<#
.SYNOPSIS
    Builds the FileBrowser (dired) manual test tree: attribute specimens, links of
    every kind, and the targets they point to.

.DESCRIPTION
    Names:
        Each name spells out what the item is: Hidden, System, ReadOnly, Junction,
        Symlink, Hardlink, ... "Invalid (...)" marks links that are expected to fail.
        "Loop (Self)" points at itself and never resolves; "Loop (Root)" points at
        the root, resolves fine and nests forever.
        Junctions and symlinks are reparse points; hard links are not.
        "Excluded" items are meant to match dired_hidden_files_patterns.

    Numbering:
        A folder and a file with the same number are counterparts (the file has an
        extension). 0x / .0 plain folders and files, 2x junctions and hard links,
        3x symlinks, 4x executables, 90 link targets.

    Every file's content says where it lives, so opening something through a link
    shows where you actually ended up. Links point into "90 Targets".

    Creating symlinks needs an elevated shell (or Developer Mode). -Preview needs
    neither: it creates the same names as plain folders/files without attributes
    and replaces links with placeholders that describe them.

.PARAMETER Path
    Root of the tree. Default: ~\dired-test-tree

.PARAMETER Preview
    Plain folders/files only: no attributes, no links (placeholders instead).

.PARAMETER Force
    Wipe a non-empty Path first. Links are removed without touching their targets.

.EXAMPLE
    .\etc\init-dired-test-tree.ps1 -Force                     # elevated
.EXAMPLE
    .\etc\init-dired-test-tree.ps1 ~\dired-test-tree-preview -Preview
#>
[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$Path = (Join-Path $env:USERPROFILE 'dired-test-tree'),
    [switch]$Preview,
    [switch]$Force
)

Set-StrictMode -Version 2
$ErrorActionPreference = 'Stop'

$MarkerFile = 'README.txt'
$MarkerLine = 'dired-toggle-test tree, generated by New-DiredTestTree.ps1'
$T = '90 Targets'

# --- Specification ------------------------------------------------------------------
# Kind: Dir | File | Junction | SymlinkDir | SymlinkFile | Hardlink
# Target: path relative to the root. Relative = store the symlink target as relative.
$Spec = @(
    # Folders
    @{ Kind = 'Dir';  Name = '00 Normal' }
    @{ Kind = 'Dir';  Name = '01 Excluded' }
    @{ Kind = 'Dir';  Name = '02 Hidden';                          Attr = 'Hidden' }
    @{ Kind = 'Dir';  Name = '03 System';                          Attr = 'System' }
    @{ Kind = 'Dir';  Name = '04 Hidden + System (SuperHidden)';   Attr = 'Hidden, System' }
    @{ Kind = 'Dir';  Name = '05 ReadOnly';                        Attr = 'ReadOnly' }
    @{ Kind = 'Dir';  Name = '06 Hidden + Excluded';               Attr = 'Hidden' }
    @{ Kind = 'Dir';  Name = '.0 Dotted' }

    # Files (same numbers as their folder counterparts)
    @{ Kind = 'File'; Name = '00 Normal.txt' }
    @{ Kind = 'File'; Name = '01 Excluded.txt' }
    @{ Kind = 'File'; Name = '02 Hidden.txt';                          Attr = 'Hidden' }
    @{ Kind = 'File'; Name = '03 System.txt';                          Attr = 'System' }
    @{ Kind = 'File'; Name = '04 Hidden + System (SuperHidden).txt';   Attr = 'Hidden, System' }
    @{ Kind = 'File'; Name = '05 ReadOnly.txt';                        Attr = 'ReadOnly' }
    @{ Kind = 'File'; Name = '06 Hidden + Excluded.txt';               Attr = 'Hidden' }
    @{ Kind = 'File'; Name = '.0 Dotted.txt' }

    # Link targets
    @{ Kind = 'Dir';  Name = $T }
    @{ Kind = 'Dir';  Name = "$T\Target Folder" }
    @{ Kind = 'File'; Name = "$T\Target.txt" }

    # Junctions (folders) and hard links (files): no elevation needed
    @{ Kind = 'Junction';    Name = '20 Junction';                       Target = "$T\Target Folder" }
    # Loop (Root) resolves but nests forever; Loop (Self) never resolves (WinError 1921).
    @{ Kind = 'Junction';    Name = '21 Junction Loop (Root)';           Target = '.' }
    @{ Kind = 'Junction';    Name = '22 Junction Loop (Self)';           Target = '22 Junction Loop (Self)' }
    @{ Kind = 'Junction';    Name = '23 Junction Invalid (Broken)';      Target = "$T\Missing Folder" }
    @{ Kind = 'Hardlink';    Name = '20 Hardlink.txt';                   Target = "$T\Target.txt" }

    # Symlinks (folder and file variants share numbers)
    @{ Kind = 'SymlinkDir';  Name = '30 Symlink';                        Target = "$T\Target Folder" }
    @{ Kind = 'SymlinkDir';  Name = '31 Symlink Relative';               Target = "$T\Target Folder"; Relative = $true }
    @{ Kind = 'SymlinkDir';  Name = '32 Symlink Loop (Root)';            Target = '.' }
    @{ Kind = 'SymlinkDir';  Name = '33 Symlink Loop (Self)';            Target = '33 Symlink Loop (Self)' }
    @{ Kind = 'SymlinkDir';  Name = '34 Symlink Invalid (Broken)';       Target = "$T\Missing Folder" }
    @{ Kind = 'SymlinkFile'; Name = '30 Symlink.txt';                    Target = "$T\Target.txt" }
    @{ Kind = 'SymlinkFile'; Name = '31 Symlink Relative.txt';           Target = "$T\Target.txt"; Relative = $true }
    @{ Kind = 'SymlinkFile'; Name = '34 Symlink Invalid (Broken).txt';   Target = "$T\Missing.txt" }
    # A *file* symlink whose target is a folder: mismatched link type.
    @{ Kind = 'SymlinkFile'; Name = '35 Symlink Invalid (File to Folder)'; Target = "$T\Target Folder" }

    # Executables
    @{ Kind = 'File'; Name = '40 Script (Executable).bat'; Content = "@echo off`r`necho Hello from dired-toggle-test`r`npause`r`n" }
)
$Spec = $Spec | ForEach-Object { [pscustomobject]$_ }

# --- Helpers ---------------------------------------------------------------------------
function Test-CanSymlink {
    $id = [Security.Principal.WindowsIdentity]::GetCurrent()
    if (([Security.Principal.WindowsPrincipal]$id).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { return $true }
    $dev = Get-ItemProperty 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\AppModelUnlock' -ErrorAction SilentlyContinue
    return [bool]($dev -and $dev.PSObject.Properties['AllowDevelopmentWithoutDevLicense'] -and $dev.AllowDevelopmentWithoutDevLicense -eq 1)
}

function Remove-TreeContent([string]$dir) {
    # Never follows links: a reparse point is deleted as the link itself.
    foreach ($item in Get-ChildItem -LiteralPath $dir -Force) {
        $isDir = [bool]($item.Attributes -band [IO.FileAttributes]::Directory)
        if ($item.Attributes -band [IO.FileAttributes]::ReparsePoint) {
            if ($isDir) { [IO.Directory]::Delete($item.FullName, $false) } else { [IO.File]::Delete($item.FullName) }
            continue
        }
        $item.Attributes = if ($isDir) { [IO.FileAttributes]::Directory } else { [IO.FileAttributes]::Normal }
        if ($isDir) { Remove-TreeContent $item.FullName; [IO.Directory]::Delete($item.FullName, $false) }
        else { [IO.File]::Delete($item.FullName) }
    }
}

function Write-Text([string]$file, [string]$text) {
    [IO.File]::WriteAllText($file, $text, (New-Object System.Text.UTF8Encoding $false))
}

function Invoke-Mklink([string[]]$mklinkArgs) {
    $out = & cmd.exe /c mklink @mklinkArgs 2>&1
    if ($LASTEXITCODE) { throw "mklink $($mklinkArgs -join ' ') failed: $out" }
}

# --- Preconditions -------------------------------------------------------------------
if (-not $Preview -and -not (Test-CanSymlink)) {
    throw 'Creating symlinks needs an elevated shell (or Developer Mode). Re-run elevated, or use -Preview.'
}

$root = [IO.Path]::GetFullPath($Path).TrimEnd('\')
$forbidden = @([IO.Path]::GetPathRoot($root).TrimEnd('\'), $HOME.TrimEnd('\'), $env:USERPROFILE.TrimEnd('\'))
if ($forbidden -contains $root) { throw "Refusing to use '$root' as the test root." }

if (Test-Path -LiteralPath $root) {
    if (@(Get-ChildItem -LiteralPath $root -Force).Count -gt 0) {
        if (-not $Force) { throw "'$root' is not empty. Use -Force to wipe it (links are removed, their targets are left alone)." }
        $marker = Join-Path $root $MarkerFile
        $ours = (Test-Path -LiteralPath $marker) -and ((Get-Content -LiteralPath $marker -TotalCount 1) -eq $MarkerLine)
        Write-Host "Wiping $root$(if (-not $ours) { ' (not created by this script)' }) ..." -ForegroundColor Yellow
        Remove-TreeContent $root
    }
} else {
    New-Item -ItemType Directory -Path $root | Out-Null
}

# --- Build -----------------------------------------------------------------------------
$mode = if ($Preview) { 'PREVIEW (no attributes, links are placeholders)' } else { 'full' }

foreach ($s in $Spec | Where-Object Kind -eq 'Dir') {
    $dir = Join-Path $root $s.Name
    New-Item -ItemType Directory -Path $dir -Force | Out-Null
    $leaf = Split-Path $s.Name -Leaf
    Write-Text (Join-Path $dir "inside $leaf.txt") "You are inside: $($s.Name)`r`n"
}

foreach ($s in $Spec | Where-Object Kind -eq 'File') {
    $content = if ($s.PSObject.Properties['Content']) { $s.Content } else { "You are at: $($s.Name)`r`n" }
    Write-Text (Join-Path $root $s.Name) $content
}

foreach ($s in $Spec | Where-Object Kind -in 'Junction', 'SymlinkDir', 'SymlinkFile', 'Hardlink') {
    $link = Join-Path $root $s.Name
    $abs = if ($s.Target -eq '.') { $root } else { Join-Path $root $s.Target }
    $relative = $s.PSObject.Properties['Relative'] -and $s.Relative
    $stored = if ($relative) { $s.Target } else { $abs }
    $describe = "$($s.Kind) -> $stored"

    if ($Preview) {
        if ($s.Kind -in 'Junction', 'SymlinkDir') {
            New-Item -ItemType Directory -Path $link | Out-Null
            Write-Text (Join-Path $link 'PLACEHOLDER.txt') "Placeholder for $describe`r`n"
        } else {
            Write-Text $link "Placeholder for $describe`r`n"
        }
        continue
    }

    switch ($s.Kind) {
        'Junction'    { Invoke-Mklink '/J', $link, $abs }
        'SymlinkDir'  { Invoke-Mklink '/D', $link, $stored }
        'SymlinkFile' { Invoke-Mklink $link, $stored }
        'Hardlink'    { Invoke-Mklink '/H', $link, $abs }
    }
}

# README (also the marker that lets -Force recognise the tree)
$readme = @(
    $MarkerLine
    "Mode: $mode"
    ''
    'Names spell out what each item is. "Invalid (...)" links are expected to fail.'
    '"Loop (Self)" never resolves; "Loop (Root)" resolves and nests forever.'
    'Junctions and symlinks are reparse points; hard links are not.'
    '"Excluded" items are meant to match dired_hidden_files_patterns.'
    'Numbering: same number = folder / file counterparts. 0x / .0 plain items,'
    '           2x junctions + hard links, 3x symlinks, 4x executables, 90 link targets.'
    ''
    'Links:'
) + ($Spec | Where-Object Kind -in 'Junction', 'SymlinkDir', 'SymlinkFile', 'Hardlink' | ForEach-Object {
    $rel = if ($_.PSObject.Properties['Relative'] -and $_.Relative) { ' (relative)' } else { '' }
    $tgt = if ($_.Target -eq '.') { '<root>' } else { $_.Target }
    '  {0,-38} {1,-11} -> {2}{3}' -f $_.Name, $_.Kind, $tgt, $rel
})
Write-Text (Join-Path $root $MarkerFile) (($readme -join "`r`n") + "`r`n")

# Attributes last, so read-only/system items don't get in the way while building.
if (-not $Preview) {
    foreach ($s in $Spec | Where-Object { $_.PSObject.Properties['Attr'] }) {
        $item = Get-Item -LiteralPath (Join-Path $root $s.Name) -Force
        $item.Attributes = $item.Attributes -bor [IO.FileAttributes]$s.Attr
    }
}

Write-Host "Built $root ($mode)" -ForegroundColor Cyan
Get-ChildItem -LiteralPath $root -Force |
    Select-Object Mode, LinkType, Name, @{ n = 'Target'; e = { $_.Target } } |
    Format-Table -AutoSize
